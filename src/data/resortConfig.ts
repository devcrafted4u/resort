// Helper to generate functional WhatsApp URLs
export function getWhatsAppUrl(customMessage?: string, params?: { date?: string; guests?: number; packageTitle?: string }): string {
  let msg = customMessage || "Hello Sams Eden Resorts! I would like to enquire about your packages and availability.";
  
  if (params?.packageTitle) {
    msg += `\nSelected Package: ${params.packageTitle}`;
  }
  if (params?.date) {
    msg += `\nPreferred Date: ${params.date}`;
  }
  if (params?.guests) {
    msg += `\nNumber of Guests: ${params.guests}`;
  }
  
  return `https://wa.me/${resortConfig.whatsappNumber}?text=${encodeURIComponent(msg)}`;
}
